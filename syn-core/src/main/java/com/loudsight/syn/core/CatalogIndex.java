package com.loudsight.syn.core;

import com.loudsight.scriptkit.ScriptHeader;
import com.loudsight.scriptkit.ScriptLibrary;
import com.loudsight.syn.spi.CommandDescriptor;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;

/**
 * The generated catalog of a repo's scripts and syn commands (by default {@code scripts/INDEX.md}). Shared by the command
 * that writes it and the one that checks it is current. The text above the table is {@code catalog.header-file} in
 * {@code .syn/config.properties} when set, else a short generic one; the table is always generated.
 */
public final class CatalogIndex {

    private static final String DEFAULT_HEADER = """
            # Script library

            Generated by `syn script-list-catalog --markdown` — do not hand-edit; `syn script-check-conventions` fails when
            this file is stale.

            **Before writing a command or script, search this list** — `syn catalog <term>` searches the commands the same way.

            **Tiers:** `read-only` — run freely · `local-mutate` — changes this machine or the repo; run and report ·
            `remote-mutate` — changes a remote host; run only when asked · `irreversible` — cannot be undone; a human runs it.
            """;

    private static final String TABLE_HEAD = """
            | Command or script | Tier | Purpose | Keywords |
            |---|---|---|---|
            """;

    private CatalogIndex() {
    }

    /** What the catalog should say: the header, then the scripts, then the commands. */
    public static String markdown(Path root, List<CommandDescriptor> commands) {
        ScriptLibrary library = ScriptLibrary.load(root);
        Path indexDir = Objects.requireNonNull(root.resolve(library.index()).getParent());
        StringBuilder out = new StringBuilder(header(root)).append("\n\n").append(TABLE_HEAD);
        for (String file : library.catalogFiles()) {
            Map<String, String> header = ScriptHeader.read(root.resolve(file));
            String link = indexDir.relativize(root.resolve(file)).toString().replace('\\', '/');
            out.append(String.format(Locale.ROOT, "| [`%s`](%s) | %s | %s | %s |%n", ScriptLibrary.commandName(file), link,
                    header.getOrDefault("tier", ""),
                    header.getOrDefault("purpose", "").replace("|", "\\|"),
                    header.getOrDefault("keywords", "").replace("|", "\\|")));
        }
        for (CommandDescriptor command : commands) {
            out.append(String.format(Locale.ROOT, "| `syn %s` | %s | %s | %s |%n", command.name(), command.tier(),
                    command.purpose().replace("|", "\\|"), String.join(", ", command.keywords()).replace("|", "\\|")));
        }
        return out.toString();
    }

    /** Whether the catalog on disk matches what would be generated now. */
    public static boolean isCurrent(Path root, List<CommandDescriptor> commands) {
        Path index = root.resolve(ScriptLibrary.load(root).index());
        try {
            return Files.exists(index) && markdown(root, commands).equals(Files.readString(index, StandardCharsets.UTF_8));
        } catch (IOException e) {
            return false;
        }
    }

    private static String header(Path root) {
        return SynConfig.load(root).path("catalog.header-file").map(file -> {
            try {
                return Files.readString(file, StandardCharsets.UTF_8);
            } catch (IOException e) {
                throw new java.io.UncheckedIOException("cannot read catalog.header-file " + file, e);
            }
        }).orElse(DEFAULT_HEADER).stripTrailing();
    }
}
