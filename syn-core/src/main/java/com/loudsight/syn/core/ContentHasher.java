package com.loudsight.syn.core;

import com.loudsight.useful.helper.logging.LoggingHelper;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.List;
import java.util.Optional;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Deterministic content hashes for directories: the digest runs over each file's path (relative to
 * the directory) and bytes, in sorted order, so it captures uncommitted changes and does not depend
 * on git. Ported from auto-agent's {@code ModuleContentHasher} with the same algorithm and the same
 * exclusions, so a hash computed here equals the one auto-agent computes for the same tree.
 */
public final class ContentHasher {

    public static final String NO_CONTENT_HASH = "nohash";

    private static final LoggingHelper LOGGER = LoggingHelper.wrap(ContentHasher.class);

    /**
     * Build output that must never reach the digest: anything here is regenerated by running the
     * build, so hashing it makes a module's hash depend on its own last build. The Playwright entries
     * are real: modules/backend-server writes browser traces to src/test/integration/playwright/
     * test-results, inside src, and digesting those 27MB of trace.zip made every build change its own
     * hash (observed 2026-08-09: 5 distinct hashes across 6 runs with no source change).
     */
    private static final Set<String> EXCLUDED_DIRS = Set.of(
            "target",
            "node_modules",
            ".git",
            ".idea",
            "dist",
            "build.log",
            "test-results",
            "playwright-report",
            "blob-report");

    private final Path projectRoot;

    public ContentHasher(Path projectRoot) {
        this.projectRoot = projectRoot.normalize();
    }

    /**
     * The SHA-256 of the directory at {@code relativePath} (relative to the project root), or
     * {@link #NO_CONTENT_HASH} when it is missing or unreadable.
     */
    public String hashModule(String relativePath) {
        return digestOf(relativePath).orElse(NO_CONTENT_HASH);
    }

    private Optional<String> digestOf(String relativePath) {
        Path modulePath = projectRoot.resolve(sanitize(relativePath)).normalize();
        if (!Files.exists(modulePath)) {
            LOGGER.logWarn("Module path does not exist: {}", modulePath);
            return Optional.empty();
        }
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            for (Path file : collectFiles(modulePath)) {
                digest.update(modulePath.relativize(file).toString().getBytes(StandardCharsets.UTF_8));
                digest.update((byte) 0);
                try (InputStream in = Files.newInputStream(file)) {
                    byte[] buffer = new byte[8192];
                    for (int read = in.read(buffer); read >= 0; read = in.read(buffer)) {
                        digest.update(buffer, 0, read);
                    }
                }
            }
            return Optional.of(HexFormat.of().formatHex(digest.digest()));
        } catch (NoSuchAlgorithmException e) {
            LOGGER.logError("SHA-256 algorithm not available: {}", e.getMessage());
            return Optional.empty();
        } catch (IOException e) {
            LOGGER.logWarn("Failed to hash module {} (IO error): {}", relativePath, e.getMessage());
            return Optional.empty();
        }
    }

    /**
     * One hash over several directories: the digest of their names and individual hashes. Empty when
     * any directory is missing or unreadable, so a broken tree never looks fresh.
     */
    public Optional<String> hashModules(List<String> relativePaths) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            for (String relativePath : relativePaths) {
                Optional<String> hash = digestOf(relativePath);
                if (hash.isEmpty()) {
                    return Optional.empty();
                }
                digest.update((relativePath + '=' + hash.get() + '\n').getBytes(StandardCharsets.UTF_8));
            }
            return Optional.of(HexFormat.of().formatHex(digest.digest()));
        } catch (NoSuchAlgorithmException e) {
            LOGGER.logError("SHA-256 algorithm not available: {}", e.getMessage());
            return Optional.empty();
        }
    }

    private List<Path> collectFiles(Path modulePath) throws IOException {
        try (Stream<Path> stream = Files.walk(modulePath)) {
            return stream.filter(Files::isRegularFile).filter(this::isNotInExcludedDir).sorted().toList();
        }
    }

    /**
     * Whether {@code file} sits outside every excluded directory, at any depth. Only the portion
     * below the project root is examined: the absolute prefix is not ours to judge, and a checkout
     * under a directory named {@code dist}, or any dot-directory, would otherwise exclude everything.
     */
    private boolean isNotInExcludedDir(Path file) {
        Path relative = file.startsWith(projectRoot) ? projectRoot.relativize(file) : file;
        for (Path part : relative) {
            String name = part.toString();
            if (EXCLUDED_DIRS.contains(name)) {
                return false;
            }
            // Hidden directories are excluded, except .meta, which affects builds.
            if (name.startsWith(".") && !".meta".equals(name)) {
                return false;
            }
        }
        return true;
    }

    private static String sanitize(String relativePath) {
        if (relativePath == null || relativePath.isBlank() || ".".equals(relativePath)) {
            return ".";
        }
        return relativePath.startsWith("./") ? relativePath.substring(2) : relativePath;
    }
}
